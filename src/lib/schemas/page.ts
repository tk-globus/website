// Схема «Сторінка» (специфікація 0001, модуль 1): статичні розділи «Про клуб», «МКК», «Табір».
// Одна схема на двох: збірка сайту (src/content.config.ts) і тест імпортера (tests/scripts/),
// тому тут лише `astro/zod` — без віртуальних модулів Astro. Тіло — Markdown під frontmatter.
// Імʼя файлу — адреса сторінки на сайті: about.md → /about (див. src/lib/pages.ts).
// Невалідний файл (немає заголовка чи опису, зайве поле) ламає збірку з поясненням.
import { z } from 'astro/zod';

export const pageSchema = z
  .object({
    title: z.string().min(1),
    /** Короткий опис: для превʼю в месенджерах і пошуковиках. */
    description: z.string().min(1),
    /** Адреса оригіналу на старому сайті — для майбутніх редиректів (ADR 0004). */
    legacyUrl: z.string().url(),
  })
  .strict();
