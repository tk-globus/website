// Пагінація стрічок (новини): скільки записів на сторінці й адреси сторінок.
// Без модулів Astro — тож цей файл читають і сторінки, і смоук-тести (tests/smoke/routes.ts).
// Адреси (зі слешем у кінці, як усі сторінки сайту): перша сторінка — сама стрічка (`/news/`), далі — `/news/2/`, `/news/3/`…
// (так їх будує paginate() на сторінці стрічки src/pages/news/).

/** Новин на сторінці стрічки: сітка 3 × 3 на компʼютері. */
export const NEWS_PER_PAGE = 9;

/** Кількість сторінок стрічки (щонайменше одна — навіть порожня стрічка має сторінку). */
export const pageCount = (total: number, perPage: number) => Math.max(1, Math.ceil(total / perPage));

/** Адреса сторінки `n` стрічки з адресою `base` (`/news/`): 1 → `/news/`, 2 → `/news/2/`. */
export const pageHref = (base: string, n: number) => (n === 1 ? base : `${base}${n}/`);
